#!/usr/bin/env node
// Generates the typed API contract from the backend's OpenAPI document (ADR-013).
//
//   yarn api:generate          regenerate types from the committed snapshot (openapi/v1.json)
//   yarn api:generate --pull   fetch the live document first and update the snapshot
//
// The pull source defaults to a locally running backend; override with OPENAPI_URL.
// The backend publishes paths with their version prefix (/api/v1/auth/me). The prefix is
// stripped here so feature code writes "/auth/me" and the version lives only in the
// client's base path.
import openapiTS, { astToString } from "openapi-typescript";
import { mkdir, readFile, writeFile } from "node:fs/promises";

const VERSION_PREFIX = "/api/v1";
const SNAPSHOT = new URL("../openapi/v1.json", import.meta.url);
const OUTPUT = new URL("../src/generated/api/v1.ts", import.meta.url);
const OPENAPI_URL =
  process.env.OPENAPI_URL ?? `http://127.0.0.1:8000${VERSION_PREFIX}/openapi.json`;

async function loadDocument() {
  if (!process.argv.includes("--pull")) {
    return JSON.parse(await readFile(SNAPSHOT, "utf8"));
  }
  const response = await fetch(OPENAPI_URL);
  if (!response.ok) {
    throw new Error(`GET ${OPENAPI_URL} failed: ${response.status} ${response.statusText}`);
  }
  const document = await response.json();
  await writeFile(SNAPSHOT, `${JSON.stringify(document, null, 2)}\n`);
  console.log(`Updated snapshot from ${OPENAPI_URL}`);
  return document;
}

function stripVersionPrefix(document) {
  const paths = {};
  for (const [path, item] of Object.entries(document.paths ?? {})) {
    if (!path.startsWith(`${VERSION_PREFIX}/`)) {
      throw new Error(`Path ${path} is outside ${VERSION_PREFIX}; is this the v1 document?`);
    }
    paths[path.slice(VERSION_PREFIX.length)] = item;
  }
  return { ...document, paths };
}

const document = stripVersionPrefix(await loadDocument());
const ast = await openapiTS(document);
const header = [
  "// Generated by scripts/generate-api.mjs from openapi/v1.json. Do not edit by hand.",
  `// Paths are relative to ${VERSION_PREFIX}.`,
  "",
].join("\n");

await mkdir(new URL(".", OUTPUT), { recursive: true });
await writeFile(OUTPUT, header + astToString(ast));
console.log(`Wrote ${Object.keys(document.paths).length} paths to src/generated/api/v1.ts`);
